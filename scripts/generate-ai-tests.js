const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'e2e', 'ai-generated.spec.js');
const DEFAULT_MODEL = 'gemini-3.5-flash';

function loadEnv(file = path.join(ROOT, '.env')) {
  if (!fs.existsSync(file)) return;
  for (const rawLine of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (!match || process.env[match[1]]) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    process.env[match[1]] = value;
  }
}

function readContext() {
  const files = [
    'src/main/java/com/example/datetimechecker/service/DateTimeCheckerService.java',
    'src/main/java/com/example/datetimechecker/controller/DateTimeCheckerController.java',
    'src/main/resources/static/index.html',
    'src/test/java/com/example/datetimechecker/DateTimeCheckerServiceTest.java',
    'e2e/ai-assisted.spec.js',
  ];
  return files.map((file) => `\n===== ${file} =====\n${fs.readFileSync(path.join(ROOT, file), 'utf8')}`).join('');
}

const responseSchema = {
  type: 'ARRAY',
  minItems: 6,
  maxItems: 15,
  items: {
    type: 'OBJECT',
    properties: {
      name: { type: 'STRING', description: 'A concise unique Vietnamese test name' },
      risk: { type: 'STRING', description: 'Requirement or defect risk protected by this test' },
      day: { type: 'STRING' },
      month: { type: 'STRING' },
      year: { type: 'STRING' },
      expectedMessage: { type: 'STRING' },
      valid: { type: 'BOOLEAN' },
    },
    required: ['name', 'risk', 'day', 'month', 'year', 'expectedMessage', 'valid'],
  },
};

function validateCases(value) {
  if (!Array.isArray(value) || value.length < 1) throw new Error('Gemini did not return a non-empty array.');
  const names = new Set();
  return value.map((item, index) => {
    for (const key of ['name', 'risk', 'day', 'month', 'year', 'expectedMessage']) {
      if (typeof item?.[key] !== 'string') throw new Error(`Case ${index + 1}: ${key} must be a string.`);
    }
    if (typeof item.valid !== 'boolean') throw new Error(`Case ${index + 1}: valid must be boolean.`);
    if (names.has(item.name)) throw new Error(`Duplicate test name: ${item.name}`);
    names.add(item.name);
    return {
      name: item.name.slice(0, 160),
      risk: item.risk.slice(0, 300),
      day: item.day,
      month: item.month,
      year: item.year,
      expectedMessage: item.expectedMessage,
      valid: item.valid,
    };
  });
}

function renderSpec(cases, model) {
  return `// AUTO-GENERATED by Gemini (${model}). Review before committing.\n` +
`const { test, expect } = require('@playwright/test');\n\n` +
`const cases = ${JSON.stringify(cases, null, 2)};\n\n` +
`test.describe('Gemini AI-assisted scenarios', () => {\n` +
`  for (const scenario of cases) {\n` +
`    test(scenario.name, async ({ page }) => {\n` +
`      test.info().annotations.push({ type: 'risk', description: scenario.risk });\n` +
`      await page.goto('/');\n` +
`      await page.getByLabel('Day', { exact: true }).fill(scenario.day);\n` +
`      await page.getByLabel('Month', { exact: true }).fill(scenario.month);\n` +
`      await page.getByLabel('Year', { exact: true }).fill(scenario.year);\n` +
`      await page.getByRole('button', { name: 'Check', exact: true }).click();\n` +
`      const result = page.locator('#result');\n` +
`      await expect(result).toHaveText(scenario.expectedMessage);\n` +
`      await expect(result).toHaveCSS('color', scenario.valid ? 'rgb(0, 128, 0)' : 'rgb(255, 0, 0)');\n` +
`    });\n` +
`  }\n` +
`});\n`;
}

async function generate() {
  loadEnv();
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'your_gemini_api_key_here') {
    throw new Error('Missing GEMINI_API_KEY. Copy .env.example to .env and paste your Gemini API key.');
  }
  const model = process.env.GEMINI_MODEL || DEFAULT_MODEL;
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`;
  const prompt = `You are a senior QA engineer. Generate risk-based Playwright UI test data for this date checker.\n` +
    `Derive expected results from the stated UI/service contract, include boundaries, Gregorian leap-year rules, invalid input and validation order.\n` +
    `Do not invent selectors or change application code. Avoid duplicating equivalent cases. Return only schema-compliant data.\n${readContext()}`;

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'x-goog-api-key': apiKey },
    body: JSON.stringify({
      contents: [{ role: 'user', parts: [{ text: prompt }] }],
      generationConfig: { temperature: 0.2, responseMimeType: 'application/json', responseSchema },
    }),
  });
  if (!response.ok) {
    const detail = (await response.text()).slice(0, 1000);
    throw new Error(`Gemini API failed (${response.status}): ${detail}`);
  }
  const body = await response.json();
  const text = body.candidates?.[0]?.content?.parts?.map((part) => part.text || '').join('');
  if (!text) throw new Error(`Gemini returned no text (finish reason: ${body.candidates?.[0]?.finishReason || 'unknown'}).`);
  const cases = validateCases(JSON.parse(text));
  fs.writeFileSync(OUTPUT, renderSpec(cases, model), 'utf8');
  console.log(`Generated ${cases.length} Gemini-assisted cases: ${path.relative(ROOT, OUTPUT)}`);
}

if (require.main === module) {
  generate().catch((error) => {
    console.error(`AI generation failed: ${error.message}`);
    process.exitCode = 1;
  });
}

module.exports = { loadEnv, validateCases, renderSpec };
